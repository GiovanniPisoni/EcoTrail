<script setup>
import { ref, watch } from 'vue'
import api from '@/api/client.js'
import BaseButton from '@/components/base/BaseButton.vue'

const props = defineProps({
  trailId: {
    type: String,
    required: true
  },
  status: {
    type: String,
    required: true
  }
})

const emit = defineEmits(['show'])

const suggestion = ref(null)
const loading = ref(false)
let requestSeq = 0

async function loadSuggestion() {
  const seq = ++requestSeq
  suggestion.value = null
  loading.value = true

  try {
    const { data } = await api.get(`/trails/${props.trailId}/alternative`)
    if (seq === requestSeq) suggestion.value = data
  } catch (err) {
    if (seq === requestSeq) console.error('Failed to load the alternative trail:', err)
  } finally {
    if (seq === requestSeq) loading.value = false
  }
}

watch(() => [props.trailId, props.status], loadSuggestion, { immediate: true })
</script>

<template>
  <section v-if="loading || suggestion" class="trail-alternative" @click.stop>
    <h3 class="trail-alternative__title">Suggested alternative</h3>

    <p v-if="loading" class="trail-alternative__loading">Looking for an alternative…</p>

    <template v-else-if="suggestion.alternative">
      <p class="trail-alternative__name">{{ suggestion.alternative.name }}</p>
      <p class="trail-alternative__reason">{{ suggestion.reason }}</p>
      <p class="trail-alternative__source">
        {{ suggestion.source === 'ai' ? 'Generated by AI' : 'Closest free trail' }}
      </p>
      <BaseButton
        variant="secondary"
        class="trail-alternative__button"
        @click="emit('show', suggestion.alternative.id)"
      >
        Show on map
      </BaseButton>
    </template>

    <p v-else class="trail-alternative__reason">{{ suggestion.reason }}</p>
  </section>
</template>

